// Release builds must never fall back to the debug key: fail as soon as a release task is scheduled
// without the signing environment. Debug builds are unaffected.
val releaseSigningEnv = listOf(
    "ANDROID_KEYSTORE_PATH",
    "ANDROID_KEYSTORE_PASSWORD",
    "ANDROID_KEY_ALIAS",
    "ANDROID_KEY_PASSWORD"
)
gradle.taskGraph.whenReady {
    val wantsRelease = allTasks.any { it.project == project && it.name.contains("Release") }
    if (wantsRelease) {
        val missing = releaseSigningEnv.filter { System.getenv(it).isNullOrBlank() }
        if (missing.isNotEmpty()) {
            throw GradleException(
                "Android release 서명 환경 변수가 없습니다: ${missing.joinToString()} (docs/android-signing.md 참고)"
            )
        }
    }
}

