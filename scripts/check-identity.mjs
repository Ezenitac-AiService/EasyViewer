/** Literals that are protocol/storage names rather than app identity. */
const INTERNAL_LITERALS = ['EasyViewerDB', 'X-EasyViewer-Proxy']

function isAllowed(rel) {
  return ALLOWED_PATHS.some((p) => (p.endsWith('/') ? rel.startsWith(p) : rel === p))
}

/** Blanks a match while keeping its newlines, so reported line numbers stay accurate. */
const blank = (m) => m.replace(/[^\n]/g, ' ')

/** Removes the parts of a text where the upstream name may legitimately appear. */
export function maskAllowed(text) {
  let out = text.replace(/<!-- support-scope:start -->[\s\S]*?<!-- support-scope:end -->/g, blank)
  // Repository slugs and URLs (the fork repository keeps the EasyViewer slug), also regex-escaped
  out = out.replace(/[\w.-]+\\?\/EasyViewer\b/g, blank)
  // Attribution to the original work
  out = out.replace(/(원저작자(의)?|원작|edith2580의|original)\s*\[?EasyViewer\]?/g, blank)
  for (const lit of INTERNAL_LITERALS) out = out.split(lit).join(blank(lit))
  return out
}

function walk(root, rel, out) {
  const abs = path.join(root, rel)
  if (!fs.existsSync(abs)) return out
  const st = fs.statSync(abs)
  if (st.isFile()) {
    if (TEXT_EXT.test(rel)) out.push(rel)
    return out
  }
  for (const name of fs.readdirSync(abs).sort()) {
    if (SKIP_DIRS.has(name)) continue
    walk(root, path.posix.join(rel, name), out)
  }
  return out
}

function read(root, rel) {
  const p = path.join(root, rel)
  return fs.existsSync(p) ? fs.readFileSync(p, 'utf-8') : null
}

function lineOf(text, index) {
  return text.slice(0, index).split('\n').length
}

export function checkLegacyTokens(root) {
  const errors = []
  const files = []
  for (const r of SCAN_ROOTS) walk(root, r, files)
  for (const rel of files) {
    if (isAllowed(rel)) continue
    const text = read(root, rel)
    if (text === null) continue
    const masked = maskAllowed(text)
    for (const { re, label } of LEGACY_TOKENS) {
      re.lastIndex = 0
      const m = re.exec(masked)
      if (m) errors.push(`${rel}:${lineOf(masked, m.index)}: 원저작자 앱 정체성 "${label}"이 남아 있습니다`)
    }
  }
  return errors
}

function cargoField(toml, section, field) {
  const m = new RegExp(`\\[${section}\\]([\\s\\S]*?)(?:\\r?\\n\\[|$)`).exec(toml)
  if (!m) return ''
  return new RegExp(`^\\s*${field}\\s*=\\s*"([^"]+)"`, 'm').exec(m[1])?.[1] ?? ''
}

export function checkManifests(root) {
  const errors = []
  const want = NEW_IDENTITY
  const expect = (label, actual, expected) => {
    if (actual !== expected) errors.push(`${label}: "${actual ?? ''}" != "${expected}"`)
  }

  const confText = read(root, 'src-tauri/tauri.conf.json')
  if (confText !== null) {
    const conf = JSON.parse(confText)
    expect('tauri.conf.json productName', conf.productName, want.productName)
    expect('tauri.conf.json identifier', conf.identifier, want.appId)
    expect('tauri.conf.json app.windows[0].title', conf.app?.windows?.[0]?.title, want.productName)
    if (String(conf.bundle?.iOS?.developmentTeam ?? '').trim()) {
      errors.push('tauri.conf.json bundle.iOS.developmentTeam: Apple 팀 ID를 저장소에 고정하지 마세요(APPLE_DEVELOPMENT_TEAM 사용)')
    }
  }

  const androidText = read(root, 'src-tauri/tauri.android.conf.json')
  if (androidText !== null) expect('tauri.android.conf.json identifier', JSON.parse(androidText).identifier, want.appId)

  const cargo = read(root, 'src-tauri/Cargo.toml')
  if (cargo !== null) {
    expect('Cargo.toml [package] name', cargoField(cargo, 'package', 'name'), want.packageName)
    expect('Cargo.toml [lib] name', cargoField(cargo, 'lib', 'name'), want.libName)
  }

  const pkgText = read(root, 'package.json')
  if (pkgText !== null) {
    const pkg = JSON.parse(pkgText)
    expect('package.json name', pkg.name, want.packageName)
    for (const [name, cmd] of Object.entries(pkg.scripts ?? {})) {
      if (/[0-9A-F]{8}-[0-9A-F]{16}/i.test(String(cmd))) {
        errors.push(`package.json scripts.${name}: iOS 기기 UDID를 저장소에 고정하지 마세요(IOS_DEVICE_ID 사용)`)
      }
    }
  }

  const yml = read(root, 'src-tauri/gen/apple/project.yml')
  if (yml !== null) {
    expect('project.yml PRODUCT_NAME', /PRODUCT_NAME:\s*"?([^"\s]+)"?/.exec(yml)?.[1], want.productName)
    if (/DEVELOPMENT_TEAM:\s*\S+/.test(yml)) {
      errors.push('project.yml DEVELOPMENT_TEAM: Apple 팀 ID를 저장소에 고정하지 마세요')
    }
  }

  const strings = read(root, 'src-tauri/gen/android/app/src/main/res/values/strings.xml')
  if (strings !== null) {
    const appName = /<string name="app_name">"?([^"<]*)"?<\/string>/.exec(strings)?.[1]
    expect('Android strings.xml app_name', appName, want.productName)
  }
  return errors
}

export function checkStorageKeys(root) {
  const errors = []
  for (const { file, literal } of STORAGE_KEYS) {
    const text = read(root, file)
    if (text === null) errors.push(`${file}: 파일이 없습니다(내부 저장 키 "${literal}" 확인 불가)`)
    else if (!text.includes(literal)) {
      errors.push(`${file}: 내부 저장 키 "${literal}"이 바뀌었습니다. 데이터 연속성을 위해 유지해야 합니다(data-model §4)`)
    }
  }
  return errors
}

export function checkIcons(root, legacyIconHashes = LEGACY_ICON_HASHES) {
  const errors = []
  for (const [rel, legacy] of Object.entries(legacyIconHashes)) {
    const abs = path.join(root, rel)
    if (!fs.existsSync(abs)) continue
    const hash = crypto.createHash('sha256').update(fs.readFileSync(abs)).digest('hex')
    if (hash === legacy) errors.push(`${rel}: 원저작자 아이콘과 같습니다. 새 아이콘으로 교체하세요(FR-016)`)
  }
  return errors
}

function checkGradleSigning(root) {
  const text = read(root, 'src-tauri/gen/android/app/build.gradle.kts')
  return text === null ? [] : checkAndroidReleaseSigning(text)
}

export const ANDROID_SIGNING_ENV = Object.freeze([
  'ANDROID_KEYSTORE_PATH',
  'ANDROID_KEYSTORE_PASSWORD',
  'ANDROID_KEY_ALIAS',
  'ANDROID_KEY_PASSWORD'
])

/**
 * FR-017 / T057: release APKs are signed only with the fork-owned key supplied through the
 * environment, never with the debug key, and a missing key must stop the build.
 */
export function checkAndroidReleaseSigning(gradleText) {
  const errors = []
  const label = 'build.gradle.kts'
  const release = /getByName\("release"\)\s*\{([\s\S]*?)\n\s{8}\}/.exec(gradleText)?.[1] ?? ''
  if (!/signingConfig\s*=\s*signingConfigs\.getByName\("release"\)/.test(release)) {
    errors.push(`${label}: release 빌드는 signingConfigs.getByName("release")로 서명해야 합니다(debug 키 대체 금지)`)
  }
  if (/signingConfigs\.getByName\("debug"\)/.test(release)) {
    errors.push(`${label}: release 빌드가 debug 키로 서명합니다`)
  }
  if (!/create\("release"\)/.test(gradleText)) errors.push(`${label}: release 서명 설정(create("release"))이 없습니다`)
  for (const name of ANDROID_SIGNING_ENV) {
    if (!gradleText.includes(`System.getenv("${name}")`)) {
      errors.push(`${label}: 서명 환경 변수 ${name}을 읽지 않습니다`)
    }
  }
  for (const field of ['storePassword', 'keyPassword', 'keyAlias']) {
    if (new RegExp(`${field}\\s*=\\s*"`).test(gradleText)) {
      errors.push(`${label}: ${field} 값을 저장소에 고정하지 마세요`)
    }
  }
  if (!/GradleException/.test(gradleText)) {
    errors.push(`${label}: 서명 환경 변수가 없을 때 GradleException으로 release 빌드를 멈춰야 합니다`)
  }
  return errors
}

export function checkIdentity(root = process.cwd(), { legacyIconHashes = LEGACY_ICON_HASHES } = {}) {
  const errors = [
    ...checkManifests(root),
    ...checkStorageKeys(root),
    ...checkIcons(root, legacyIconHashes),
    ...checkGradleSigning(root),
    ...checkLegacyTokens(root)
  ]
  return { ok: errors.length === 0, errors }
}

function main() {
  const res = checkIdentity(process.cwd())
  if (!res.ok) {
    for (const e of res.errors) console.error(`[check:identity] ${e}`)
    process.exit(1)
  }
  console.log(`[check:identity] 앱 정체성 확인: ${NEW_IDENTITY.productName} (${NEW_IDENTITY.appId})`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main()
}
